"""Typed Python code from manifests: a label or field change breaks the build instead of production."""

import re

from jeff.catalogue import Catalogue
from jeff.errors import JeffError
from jeff.ids import parse_ref
from jeff.manifest import FunctionSpec


def class_name(function_id: str) -> str:
    parts = re.split(r"[^a-zA-Z0-9]+", function_id.removeprefix("jeff."))
    words: list[str] = []
    for part in parts:
        if not part:
            continue
        if part[0].isdigit():
            # A class name cannot start, nor (after CamelCasing) contain a word boundary landing on, a digit;
            # "N" keeps the part readable and the whole name a valid identifier wherever it falls.
            part = "N" + part
        words.append(part[:1].upper() + part[1:])
    return "".join(words)


def value_type(function: FunctionSpec) -> str:
    if function.type == "noul":
        return "bool"
    if function.type == "score":
        return f"Literal[{', '.join(str(i) for i in range(len(function.labels.levels)))}]"
    if function.labels.source == "caller":
        return "str"
    if function.labels.source == "describe":
        return f"Literal[{', '.join(repr(key) for key in function.labels.keys)}]"
    # fixed or subset: the universe of allowed answers is labels.fixed either way.
    return f"Literal[{', '.join(repr(key) for key in function.labels.fixed)}]"


def _runtime_check(function: FunctionSpec, kind: str) -> str:
    """The exact check for a decision's value at the kind it is generated as. `bool` is a subclass of `int` in
    Python (`True == 1`), so a plain `isinstance`/membership check alone would let a score's `1` through a `bool`
    check, or a `noul`'s `True` through a score's `Literal[0, 1, ...]` membership check. Pinning `type(...) is
    ...` first rules that out in every case."""
    if kind == "bool":
        return "type(decision.value) is bool"
    if kind == "str":
        return "type(decision.value) is str"
    member_type = "int" if function.type == "score" else "str"
    return f"type(decision.value) is {member_type} and decision.value in {kind[len('Literal'):]}"


def context_type(function: FunctionSpec) -> str:
    """The function's context as a TypedDict, by code name (its own fields, or its adapter's): each value any JSON,
    required or not as the manifest says. A function with no context fields gets an empty one."""
    fields = ", ".join(f"{field.code_name!r}: {'Required' if field.required else 'NotRequired'}[JSON]"
                       for field in function.context)
    return f"TypedDict('Context', {{{fields}}})"


def input_type(function: FunctionSpec) -> str:
    """The input's type: a string for a plain-text input (form text), any JSON value for a named-field one."""
    return "str" if function.input.form == "text" else "JSON"


def python_module(catalogue: Catalogue, refs: list[str]) -> str:
    functions: list[FunctionSpec] = []
    for ref in refs:
        if parse_ref(ref).key is not None:
            functions.append(catalogue.function(ref))
        else:
            functions.extend(catalogue.adapter(ref).functions.values())
    unique: list[FunctionSpec] = []
    seen_ids: set[str] = set()
    class_name_of: dict[str, str] = {}
    for function in functions:
        if function.id in seen_ids:
            continue  # the same function, requested twice (e.g. by its adapter and by itself): emit it once
        seen_ids.add(function.id)
        name = class_name(function.id)
        if name in class_name_of:
            raise JeffError(f"{function.id} and {class_name_of[name]} both produce the class name {name}; "
                            "rename one of the functions or request only one of them")
        class_name_of[name] = function.id
        unique.append(function)
    lines = ['"""Generated by `jeff gen`; do not edit."""', "",
             "from typing import Final, Literal, NotRequired, Required, TypedDict", "",
             "from jeff import Decision", "from jeff.binding import JSON", ""]
    for function in unique:
        name, kind = class_name(function.id), value_type(function)
        check = _runtime_check(function, kind)
        lines += ["", f"class {name}:", f"    id: Final = {function.id!r}", f"    type Value = {kind}",
                  "    # the context to bind it with (context=), by code name, and the input each call passes",
                  f"    Context = {context_type(function)}", f"    type Input = {input_type(function)}", "",
                  "    @staticmethod", f"    def value(decision: Decision) -> {kind}:",
                  f"        if decision.function != {function.id!r}:",
                  f"            raise TypeError(f\"expected a decision of {function.id}, got {{decision.function}}\")",
                  f"        if not ({check}):",
                  "            raise TypeError(f\"value {decision.value!r} is outside the generated type\")"]
        if kind.startswith("Literal"):
            # The membership half of `check` does not narrow decision.value's static type (str | bool | int) down
            # to the Literal, even though the `type(...) is ...` half makes the runtime check exact.
            lines += ["        return decision.value  # type: ignore[return-value]", ""]
        else:
            # `type(decision.value) is {kind}` narrows decision.value to exactly `kind` here, so no ignore needed.
            lines += ["        return decision.value", ""]
    return "\n".join(lines)
